#!/usr/bin/env node
/**
 * scripts/generate-dataset-manifest.js
 *
 * Scans apps/ckt/datasets/ and writes apps/ckt/dataset-manifest.json.
 *
 * Rule 3: the app reads a generated list and nothing walks a directory. The
 * list is small but the *counts* are the useful part — a dataset's glyph count
 * is what a panel needs to bound its index control, and reading nine files of
 * two megabytes to find out would be absurd at boot.
 *
 * ── What these files are ────────────────────────────────────────────────────
 *
 * The nine datasets ColorKineType v2 shipped as `data/json_data_1..9.json`,
 * renamed after v2's own `ListNameFonts` in the same order — alphabet,
 * raleway, egypt, garam, peace, pilow, mainz, destra, minipax. Seven are
 * byte-identical to v2's files; alphabet and mainz differ only in whitespace.
 *
 * The names line up with the hand-made sprite families: garam and peace are
 * 58 glyphs like Garam_blue and Ps_pink, minipax and raleway 78 like
 * minipax_white and Raleway_green. destra is 76 against Destra_yellow's 78.
 * Those families are this data with a pattern drawn on every dot — the chain
 * M3 exists to make repeatable.
 *
 * Shape is `[glyph][point][x, y]` in the pixels of the canvas the blobs were
 * found on. Nothing normalises them: ckt centres each glyph when it draws it,
 * as v2's boundingBox() did. See docs/object-model.md's `dataset` type.
 *
 * Run from the project root:
 *   node scripts/generate-dataset-manifest.js
 */

const fs = require('fs');
const path = require('path');

const DIR    = path.join(__dirname, '..', 'apps', 'ckt', 'datasets');
const OUTPUT = path.join(__dirname, '..', 'apps', 'ckt', 'dataset-manifest.json');

function build() {
  if (!fs.existsSync(DIR)) {
    console.error('no apps/ckt/datasets/ — nothing to do');
    process.exit(1);
  }

  const files = fs.readdirSync(DIR).filter(f => f.endsWith('.json')).sort();

  const datasets = files.map(file => {
    const id = path.basename(file, '.json');
    const raw = JSON.parse(fs.readFileSync(path.join(DIR, file), 'utf8'));

    if (!Array.isArray(raw)) {
      console.error(`  ${id}: not an array of glyphs — skipped`);
      return null;
    }

    const counts = raw.map(g => (Array.isArray(g) ? g.length : 0));
    const points = counts.reduce((a, b) => a + b, 0);

    return {
      id,
      file: `datasets/${file}`,
      glyphs: raw.length,
      points,
      // Per-glyph counts, so a panel can warn before you pick the 476-point
      // one and wonder why it slowed down.
      perGlyph: { min: Math.min(...counts), max: Math.max(...counts),
                  mean: Math.round(points / Math.max(1, raw.length)) },
      bytes: fs.statSync(path.join(DIR, file)).size,
    };
  }).filter(Boolean);

  const manifest = {
    generated: new Date().toISOString(),
    note: 'Generated by scripts/generate-dataset-manifest.js — do not edit by hand.',
    shape: '[glyph][point][x, y] in canvas pixels; ckt centres each glyph when it draws it',
    datasets,
  };

  fs.writeFileSync(OUTPUT, JSON.stringify(manifest, null, 2) + '\n');

  console.log(`apps/ckt/dataset-manifest.json — ${datasets.length} datasets`);
  for (const d of datasets) {
    console.log(`  ${d.id.padEnd(10)} ${String(d.glyphs).padStart(3)} glyphs  `
      + `${String(d.points).padStart(6)} points  `
      + `(${d.perGlyph.min}–${d.perGlyph.max}, mean ${d.perGlyph.mean})`);
  }
}

build();
